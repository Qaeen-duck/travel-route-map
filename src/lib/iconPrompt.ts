/**
 * 手段 H3 · 固化 prompt 模板（PRD F3.9 / 附录 A.6）
 *
 * 版本记录：
 * - v1（当前生效）：干净描边 + 柔和笔触的贴纸风。实测「武康大楼」效果获确认采用。
 * - v2（2026-08-27 已回退）：曾把水彩物理特征写得很具体（湿画法/水痕/纸纹/飞白）
 *   并要求大幅简化细节，结果矫枉过正 —— 输出变成了完整的风景水彩画：
 *   主体边缘糊化、丢失贴纸描边、还自行补出背景树木和云，
 *   违反附录 A.4「单一主体居中、白底、无背景」。故整体回退到 v1，不再保留 v2 措辞。
 *
 * 结论（供后续调优参考）：本产品要的是「插画贴纸」，不是「水彩画作」。
 * 「水彩」在这里只是笔触和配色的修饰语，主语始终是「贴纸图标」，加码时别把主语盖过去。
 *
 * 关于「参照强度」：千问图像生成与编辑 3.0 没有 strength 参数（v1.2 已改为 A 方案，
 * 用措辞控制）。「保留主体轮廓与辨识度」+「整体重画、不要写实质感」这两句是
 * 专属感与风格统一之间的平衡点，调效果时优先动它们。
 */

/** 反向提示词：把附录 A.1 的禁用色和 A.2 的反例写成排除项 */
export const NEGATIVE_PROMPT = [
  '照片写实质感',
  '高饱和电子色',
  '荧光色',
  '纯黑',
  '文字',
  '水印',
  '人物',
  '人脸',
  '复杂背景',
  '多个主体',
  '矢量扁平风格',
  '几何硬边',
  '3D渲染',
].join('、');

/** 色板关键词。就算色卡参考图那条路失效，prompt 里也留一份文字约束作为兜底（F3.7 的降级方案） */
const PALETTE_WORDS = '陶土红、鼠尾草绿、奶油米、淡水彩蓝、芥末黄、淡棕';

/** 两种路径共用的画面要求（附录 A.4 图标设计原则） */
const COMMON_RULES = [
  '单一主体居中，主体占画面 60% 到 80%，四周留白',
  '白色背景，贴纸风格',
  '柔和手绘笔触，粗细不均的线条，边缘略有水彩晕染',
  '简洁可爱，画面里不要出现任何文字，不要出现人物',
].join('；');

/** 图生图（主路径）：用户照片 + 色卡参考图 */
export function buildImg2ImgPrompt(poiName: string): string {
  return [
    `请以图一的照片为素材，重新绘制成一枚手绘水彩风格的旅行贴纸图标，主体是「${poiName}」。`,
    '保留主体的轮廓与辨识度，但整体重画为水彩插画，不要保留照片的写实质感。',
    `色彩基调严格参照图二的色卡，使用${PALETTE_WORDS}这一组温暖水彩色系。`,
    `画面要求：${COMMON_RULES}。`,
  ].join('');
}

/** 文生图（补充路径）：没有照片时只用 POI 名称 */
export function buildText2ImgPrompt(poiName: string): string {
  return [
    `画一枚手绘水彩风格的旅行贴纸图标，主体是「${poiName}」。`,
    `色彩基调使用${PALETTE_WORDS}这一组温暖水彩色系。`,
    `画面要求：${COMMON_RULES}。`,
  ].join('');
}
